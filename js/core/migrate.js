// v1 → v2 migration (ARCHITECTURE §3): pure transforms + IndexedDB glue.
//
// Exactly-once by construction:
//  - every migrated event gets a DETERMINISTIC id derived from its v1 session
//    id (evt_<sessionId>), so re-running can only skip, never duplicate;
//  - the events, the mapped settings and `settings.migratedV2 = true` are
//    written in ONE transaction, so a crash leaves either nothing or all of it;
//  - v1 data is never deleted (the `sessions` store stays, read-only).
// Live timers are a separate idempotent step that runs on every boot, so a
// crash between "event written" and "localStorage key removed" self-heals.
//
// Babies (§3): v1 tracked one child. Migration puts every v1 feed (and the
// live bottle) on ONE default baby named from the v1 `babyName`; pumps are
// the parent's and get babyId: null. settings.load() may already have
// created an unnamed default baby on this boot — if so, that baby is named
// and reused rather than adding a second one.

import { transaction, STORES } from './db.js';
import { sanitizeEvent, notifyEvents, ID_RE, FUTURE_SKEW_MS, MIN_TIME } from './store.js';
import {
  deviceId as getDeviceId, get as getSetting, reload as reloadSettings, sanitizeSetting, makeBaby, cleanText, NAME_MAX,
} from './settings.js';
import { convertQty, normalizeUnit, roundForUnit, toFiniteNumber } from './units.js';

/** Note put on events whose v1 amount was NaN/null (the v1.6 NaN-pump bug). */
export const MISSING_AMOUNT_NOTE = 'Amount wasn’t recorded';
/** Note put on events whose v1 time had to be moved (saved in the future, or
 * an impossible length) so the parent knows to check it. */
export const CHECK_TIME_NOTE = 'Time was adjusted (please check)';
/** Longest a v1 feed or pump can have lasted; a longer durationSec is junk. */
export const MAX_SESSION_MS = 24 * 3600 * 1000;
/** How many rejected v1 session ids runMigration reports (the count is exact). */
const MAX_REPORTED_IDS = 50;

/** v1 localStorage keys for live timers. */
export const LIVE_TIMER_KEYS = Object.freeze({
  pump: 'nurture_active_pump_timer',
  pumpLegacy: 'savannah_active_pump_timer', // pre-release name, still migrated by v1
  bottle: 'nurture_bottle_timer',
});

// Notes v1 generated itself. They carry no user meaning ("Formula Feeding")
// and would clutter every row, so they're dropped; real notes are kept.
const AUTO_NOTES = [
  /^formula feeding$/i,
  /^breast milk feeding$/i,
  /^formula bottle feed$/i,
  /^breast milk bottle feed$/i,
  /^pumped session \(.*\)$/i,
  /^bottle feed \(.*prepared\)$/i,
];
const PREPARED_NOTE = /^bottle feed \(\s*(\d+(?:\.\d+)?)\s*(oz|ml)\s+prepared\)$/i;

/**
 * Was this note generated by v1 (not typed by a person)?
 * @param {unknown} note
 * @returns {boolean}
 */
export function isAutoNote(note) {
  if (typeof note !== 'string') return false;
  const t = note.trim();
  return AUTO_NOTES.some(re => re.test(t));
}

const own = (o, k) => (o !== null && typeof o === 'object' && Object.prototype.hasOwnProperty.call(o, k) ? o[k] : undefined);

/**
 * Deterministic v2 id for a v1 session.
 * @param {object} s
 * @returns {string}
 */
export function migratedEventId(s) {
  const id = own(s, 'id');
  if (typeof id === 'string' && ID_RE.test(id) && id.length <= 90) return `evt_${id}`;
  const start = toFiniteNumber(own(s, 'startTime'));
  return `evt_v1_${own(s, 'type') === 'pump' ? 'pump' : 'feed'}_${start === null ? 'x' : Math.round(start)}`;
}

/**
 * v1 session → v2 event (pure). Returns null for records that can't be
 * migrated (unknown type, no usable startTime).
 *
 * Feed timing: v1 stamped a feed when it was LOGGED — i.e. when it ended —
 * with `durationSec` for timed bottles (feedFlow.trackFood: startTime = now,
 * endTime = now). So the v2 feed ends at the v1 timestamp and starts
 * durationSec earlier. (Adding the duration instead would push the end of
 * every timed bottle into the future.) Pumps were stamped at the timer's
 * start with a real endTime, so they map directly.
 *
 * Feeds go to `babyId` (the default baby); pumps always get babyId null.
 *
 * Times v1 accepted are never a reason to drop the record (v1's edit modal
 * takes any date, and v1 kept and showed it): a session whose end lies more
 * than FUTURE_SKEW_MS ahead (a wrong day, a year typo) is moved to END NOW,
 * keeping its length; a durationSec over MAX_SESSION_MS is capped (and a
 * start before MIN_TIME raised to it). Either way the note gets
 * CHECK_TIME_NOTE so the parent can fix the time.
 * @param {object} s v1 session
 * @param {{ deviceId?: string, now?: number, babyId?: string }} [ctx]
 * @returns {object|null}
 */
export function sessionToEvent(s, { deviceId, now = Date.now(), babyId } = {}) {
  if (s === null || typeof s !== 'object') return null;
  const type = own(s, 'type');
  if (type !== 'pump' && type !== 'feed') return null;
  const stamp = toFiniteNumber(own(s, 'startTime'));
  if (stamp === null) return null;
  const rawDurMs = Math.max(0, toFiniteNumber(own(s, 'durationSec')) ?? 0) * 1000;
  const durMs = Math.min(rawDurMs, MAX_SESSION_MS);
  const durCapped = rawDurMs > MAX_SESSION_MS;
  let timeFixed = false;
  const unit = normalizeUnit(own(s, 'unit') || 'oz');
  const qty = toFiniteNumber(own(s, 'outputQty'));
  const amount = qty !== null && qty >= 0 ? qty : null;

  const rawNote = typeof own(s, 'notes') === 'string' ? own(s, 'notes').trim() : '';
  const userNote = isAutoNote(rawNote) ? '' : rawNote;

  let startTime;
  let endTime;
  let data;
  if (type === 'pump') {
    startTime = stamp;
    // v1 edits move startTime but leave endTime alone unless the duration
    // changes too, so an endTime that isn't a plausible end falls back to
    // the recorded duration.
    const end = toFiniteNumber(own(s, 'endTime'));
    if (end !== null && end >= stamp && end - stamp <= MAX_SESSION_MS) endTime = end;
    else { endTime = stamp + durMs; timeFixed = durCapped; }
    data = { amount, unit, storedTo: null };
  } else {
    endTime = stamp;
    startTime = stamp - durMs;
    timeFixed = durCapped;
    data = { method: 'bottle', milk: own(s, 'feedType') === 'formula' ? 'formula' : 'breastmilk', amount, unit };
    const m = PREPARED_NOTE.exec(rawNote);
    if (m) data.prepared = roundForUnit(convertQty(Number(m[1]), normalizeUnit(m[2]), unit), unit);
  }
  const latest = now + FUTURE_SKEW_MS;
  const moved = endTime > latest;
  if (moved) {
    // Saved in the future: it happened, just not then. End it now.
    startTime = now - (endTime - startTime);
    endTime = now;
    timeFixed = true;
  }
  if (startTime < MIN_TIME && endTime >= MIN_TIME) { startTime = MIN_TIME; timeFixed = true; }

  const note = [userNote, timeFixed ? CHECK_TIME_NOTE : '', amount === null ? MISSING_AMOUNT_NOTE : '']
    .filter(Boolean).join(' — ');

  // A moved session's times depend on WHEN it is migrated/imported, so its
  // stamps must not: re-importing the same v1 file must never beat the
  // parent's later fix in a newest-wins merge. (v1 always stamped createdAt;
  // this only matters for hand-made files.)
  const ownStamp = k => {
    const t = toFiniteNumber(own(s, k));
    return moved && t !== null && t > latest ? null : t;
  };
  const createdAt = ownStamp('createdAt') ?? (moved ? MIN_TIME : stamp);
  const updatedAt = ownStamp('updatedAt') ?? createdAt;
  const res = sanitizeEvent({
    id: migratedEventId(s),
    type,
    startTime,
    endTime,
    note,
    data,
    createdAt,
    updatedAt,
    babyId,
    deviceId,
    migratedFrom: typeof own(s, 'id') === 'string' ? own(s, 'id') : undefined,
  }, { now, deviceId });
  return res.ok ? res.value : null;
}

function v1SettingsMap(v1) {
  const map = Object.create(null);
  if (Array.isArray(v1)) {
    for (const r of v1) {
      const k = own(r, 'key');
      if (typeof k === 'string') map[k] = own(r, 'value');
    }
  } else if (v1 && typeof v1 === 'object') {
    for (const k of Object.keys(v1)) map[k] = v1[k];
  }
  return map;
}

/**
 * The v1 baby's name (pure): trimmed, capped, and '' for v1's 'Baby'
 * placeholder, which was never a real name.
 * @param {object[]|object} v1 the v1 settings (records or map)
 * @returns {string}
 */
export function v1BabyName(v1) {
  const raw = v1SettingsMap(v1).babyName;
  const name = cleanText(raw, NAME_MAX).trim();
  return name.toLowerCase() === 'baby' ? '' : name;
}

/**
 * Map v1 settings to v2 keys (pure). Accepts the v1 `settings` store as an
 * array of { key, value } records or as a { key: value } map. Only keys that
 * were present AND valid come out. Junk keys v1's onboarding wrote by mistake
 * (dailyPumpingGoal, reminderIntervalHours, preferredUnit — AUDIT F3) are
 * ignored on purpose.
 *
 * With `babyId`, the result also carries `babies` (one baby, named from the
 * v1 babyName) and `activeBabyId`. Without it, babies are left to the caller
 * (runMigration reuses a default baby that may already exist).
 * @param {object[]|object} v1
 * @param {{ babyId?: string, now?: number }} [ctx]
 * @returns {object} partial v2 settings
 */
export function mapV1Settings(v1, { babyId, now = Date.now() } = {}) {
  const map = v1SettingsMap(v1);
  const has = k => Object.prototype.hasOwnProperty.call(map, k);
  const out = {};
  const put = (key, value) => {
    const res = sanitizeSetting(key, value);
    if (res.ok) out[key] = res.value;
  };
  if (has('dailyGoalOz')) put('pumpGoalOz', map.dailyGoalOz);
  if (has('pumpIntervalMinutes')) put('pumpIntervalMinutes', map.pumpIntervalMinutes);
  if (has('units')) put('units', map.units);
  if (has('themeMode')) put('theme', map.themeMode);
  // v1 defaulted sound ON. Anyone who left it on gets the calmer v2 default
  // (silent at night, AUDIT §4); anyone who turned it off stays off.
  if (has('soundEnabled')) put('sound', map.soundEnabled === false ? 'off' : 'night-off');
  if (has('storageWindows')) put('storageWindows', map.storageWindows);
  if (has('parentName')) put('parentName', typeof map.parentName === 'string' ? map.parentName : '');
  if (typeof babyId === 'string') {
    put('babies', [{ id: babyId, name: v1BabyName(map), birthDate: null, photoId: null, createdAt: Number.isFinite(now) ? now : null }]);
    if (out.babies) out.activeBabyId = babyId;
  }
  if (has('onboarding_completed')) put('onboarded', map.onboarding_completed === true);
  return out;
}

function parseJson(raw) {
  if (typeof raw !== 'string' || !raw) return null;
  try { return JSON.parse(raw); } catch { return null; }
}

/**
 * v1 localStorage live timers → RUNNING v2 events (pure). Inputs are the raw
 * localStorage strings (or null). Amounts are unknown until the activity is
 * stopped, so they start null; the bottle's prepared amount (canonical oz in
 * v1) is converted to the user's unit. The bottle belongs to `babyId`; the
 * pump to the parent (null).
 * @param {{ pump?: string|null, bottle?: string|null }} raw
 * @param {{ deviceId?: string, now?: number, unit?: 'oz'|'mL', babyId?: string }} [ctx]
 * @returns {object[]}
 */
export function liveTimersToEvents({ pump, bottle } = {}, { deviceId, now = Date.now(), unit = 'oz', babyId } = {}) {
  const u = normalizeUnit(unit);
  const out = [];
  const p = parseJson(pump);
  const pumpStart = toFiniteNumber(own(p, 'startedAt'));
  if (p && own(p, 'active') && pumpStart !== null) {
    const dest = own(p, 'storeDestination');
    const res = sanitizeEvent({
      id: `evt_live_pump_${Math.round(pumpStart)}`,
      type: 'pump',
      startTime: Math.min(pumpStart, now),
      endTime: null,
      data: { amount: null, unit: u, storedTo: ['fridge', 'freezer', 'deepFreezer'].includes(dest) ? dest : null },
      createdAt: now,
      updatedAt: now,
    }, { now, deviceId });
    if (res.ok) out.push(res.value);
  }
  const b = parseJson(bottle);
  const bottleStart = toFiniteNumber(own(b, 'startTs'));
  if (b && bottleStart !== null && own(b, 'feedType')) {
    const preparedOz = toFiniteNumber(own(b, 'preparedOz'));
    const data = {
      method: 'bottle',
      milk: own(b, 'feedType') === 'formula' ? 'formula' : 'breastmilk',
      amount: null,
      unit: u,
      sourceInventoryId: own(b, 'sourceInventoryId'),
    };
    if (preparedOz !== null && preparedOz > 0) data.prepared = roundForUnit(convertQty(preparedOz, 'oz', u), u);
    const res = sanitizeEvent({
      id: `evt_live_bottle_${Math.round(bottleStart)}`,
      type: 'feed',
      startTime: Math.min(bottleStart, now),
      endTime: null,
      data,
      babyId,
      createdAt: now,
      updatedAt: now,
    }, { now, deviceId });
    if (res.ok) out.push(res.value);
  }
  return out;
}

function safeStorage(storage) {
  try {
    if (storage && typeof storage.getItem === 'function') return storage;
    return typeof localStorage !== 'undefined' ? localStorage : null;
  } catch {
    return null; // localStorage access throws when site data is blocked
  }
}

/**
 * Run the v1 → v2 migration once (idempotent; safe to call on every boot,
 * and it MUST be awaited before views mount). Also loads settings.
 * `rejected` counts the v1 sessions that could not be migrated at all (not a
 * feed/pump, or no usable time) and `rejectedIds` lists up to 50 of their
 * v1 ids, so the UI can tell the parent instead of losing them silently.
 * (They stay in the read-only v1 `sessions` store.)
 * @param {{ storage?: Storage, now?: number }} [opts] storage defaults to localStorage
 * @returns {Promise<{ skipped: boolean, events: number, rejected: number, rejectedIds: string[], settings: string[], liveTimers: number, babyId?: string }>}
 */
export async function runMigration({ storage, now = Date.now() } = {}) {
  const deviceId = await getDeviceId(); // also loads settings
  const report = await transaction([STORES.sessions, STORES.events, STORES.settings], 'readwrite', (s, ctx) => {
    const flag = s.settings.get('migratedV2');
    flag.onsuccess = () => {
      if (flag.result && flag.result.value === true) {
        ctx.done({ skipped: true, events: 0, rejected: 0, rejectedIds: [], settings: [] });
        return;
      }
      const sessionsReq = s.sessions.getAll();
      const settingsReq = s.settings.getAll();
      const keysReq = s.events.getAllKeys();
      keysReq.onsuccess = () => {
        // All three requests resolve in order within the transaction.
        const records = settingsReq.result || [];
        const byKey = new Map(records.filter(r => r && typeof r.key === 'string').map(r => [r.key, r.value]));
        const written = [];
        const { babies, babyId, changed } = planDefaultBaby(byKey.get('babies'), byKey.get('activeBabyId'), v1BabyName(records), now);
        if (changed) {
          s.settings.put({ key: 'babies', value: babies, updatedAt: now });
          written.push('babies');
        }
        if (byKey.get('activeBabyId') !== babyId) {
          s.settings.put({ key: 'activeBabyId', value: babyId, updatedAt: now });
          written.push('activeBabyId');
        }

        const existing = new Set(keysReq.result);
        let added = 0;
        let rejected = 0;
        const rejectedIds = [];
        for (const session of sessionsReq.result || []) {
          const ev = sessionToEvent(session, { deviceId, now, babyId });
          if (!ev) {
            rejected += 1;
            const sid = own(session, 'id');
            if (rejectedIds.length < MAX_REPORTED_IDS) rejectedIds.push(typeof sid === 'string' ? sid.slice(0, 100) : String(sid).slice(0, 100));
            continue;
          }
          if (existing.has(ev.id)) continue;
          existing.add(ev.id);
          s.events.put(ev);
          added += 1;
        }
        const present = new Set(byKey.keys());
        const mapped = mapV1Settings(records);
        for (const [key, value] of Object.entries(mapped)) {
          // Never clobber a v2 value (v1 and v2 share some key names, e.g.
          // units/storageWindows/pumpIntervalMinutes, with the same meaning).
          if (present.has(key)) continue;
          s.settings.put({ key, value, updatedAt: now });
          written.push(key);
        }
        s.settings.put({ key: 'migratedV2', value: true, updatedAt: now });
        written.push('migratedV2');
        ctx.done({ skipped: false, events: added, rejected, rejectedIds, settings: written, babyId });
      };
    };
  });

  // Skipped because ANOTHER tab migrated after this tab loaded its settings
  // (two tabs restored together after the update): this tab's cache still
  // holds the pre-migration defaults, so re-read it — otherwise this tab
  // would show onboarding again and later write those defaults back.
  if (!report.skipped || getSetting('migratedV2') !== true) await reloadSettings();
  const liveTimers = await migrateLiveTimers({ storage, now, deviceId, babyId: getSetting('activeBabyId') });
  if (report.events > 0 || liveTimers > 0) notifyEvents({ op: 'bulk' });
  return { ...report, liveTimers };
}

/**
 * Which baby the v1 data goes to (pure). Reuses a valid stored babies list —
 * naming its only baby from v1 if that baby is still unnamed (the default
 * settings.load() creates) — or creates the default baby. `babyId` is the
 * stored activeBabyId when it names one of the babies, else the first baby.
 * @param {unknown} storedBabies
 * @param {unknown} storedActiveId
 * @param {string} v1Name
 * @param {number} [now]
 * @returns {{ babies: object[], babyId: string, changed: boolean }}
 */
export function planDefaultBaby(storedBabies, storedActiveId, v1Name, now = Date.now()) {
  const res = sanitizeSetting('babies', storedBabies, { lenient: true });
  let babies;
  let changed = false;
  if (res.ok) {
    babies = res.value;
    if (v1Name && babies.length === 1 && !babies[0].name) {
      babies = [{ ...babies[0], name: v1Name }];
      changed = true;
    }
  } else {
    babies = [makeBaby({ name: v1Name }, now)];
    changed = true;
  }
  const babyId = babies.some(b => b.id === storedActiveId) ? storedActiveId : babies[0].id;
  return { babies, babyId, changed };
}

async function migrateLiveTimers({ storage, now, deviceId, babyId }) {
  const store = safeStorage(storage);
  if (!store) return 0;
  let raw;
  try {
    raw = {
      pump: store.getItem(LIVE_TIMER_KEYS.pump) || store.getItem(LIVE_TIMER_KEYS.pumpLegacy),
      bottle: store.getItem(LIVE_TIMER_KEYS.bottle),
    };
  } catch {
    return 0;
  }
  if (!raw.pump && !raw.bottle) return 0;
  const candidates = liveTimersToEvents(raw, { deviceId, now, unit: getSetting('units'), babyId });
  const added = await transaction(STORES.events, 'readwrite', (s, ctx) => {
    let count = 0;
    ctx.done(0);
    const all = s.events.getAll();
    all.onsuccess = () => {
      const rows = all.result || [];
      for (const ev of candidates) {
        if (rows.some(e => e.id === ev.id)) continue;
        // One running per type per baby: a v2 activity already running wins.
        if (rows.some(e => e.type === ev.type && e.endTime === null && (e.babyId ?? null) === ev.babyId)) continue;
        s.events.put(ev);
        rows.push(ev);
        count += 1;
      }
      ctx.done(count);
    };
  });
  // Only after the events are durably stored.
  try {
    store.removeItem(LIVE_TIMER_KEYS.pump);
    store.removeItem(LIVE_TIMER_KEYS.pumpLegacy);
    store.removeItem(LIVE_TIMER_KEYS.bottle);
  } catch { /* best effort */ }
  return added;
}
